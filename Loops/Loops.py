                                         # LOOPS

# A loop repeats a block of code until a condition becomes false or until it has iterated over every item.

# example 1 :
for i in range(5):
  print("Hello")  # Hello will print 5 times now 

# For Loop 

# Used when you know how many times you want to repeat something or when you're iterating over a sequence.

# Example : 
for i in range(5):
  print(i) # 0 1 2 3 4 

# Range => range() creates a sequence of numbers. 

print("Using Range")
for i in range(2,11,2):
  print(i) 

print("Negative step")
for i in range(10,0,-1):
  print(i)

